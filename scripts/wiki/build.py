"""Build the GitHub Wiki pages from the documentation of every Quizzivy repository.

usage: build.py SRC OUT [--with NAME=DIR ...] [--owner OWNER] [--strict]

SRC is a checkout of this repository (docs) and OUT a clone of the wiki or an
empty directory. Each --with adds a checkout of another repository of OWNER
(sdk, api, web), whose documentation the wiki publishes too. A relative link
resolves in the repository of the file that holds it first, then in the
others in the order given, so a plan document's link to server/ lands on
Quizzivy/api. Every page written carries MARKER. A page that carries it and is
no longer generated is removed from OUT; a page without it is never touched
unless its name is one the build writes. The build exits 1 when a link between
wiki pages does not resolve or a split loses text, and with --strict also when
a link names a path that no repository has.
"""
