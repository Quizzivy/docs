FENCE_OPEN = re.compile(r"^\s*(`{3,}|~{3,})(.*)$")
HEADING = re.compile(r"^ {0,3}(#{1,6})\s+(.+?)\s*#*\s*$")
URL_SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.\-]*:")
LINK_OR_SPAN = re.compile(
    r"""
    (?P<span>(?<!`)(?P<ticks>`+)(?!`)(?P<code>[^\n]*?[^`\n])(?<!`)(?P=ticks)(?!`))
    |(?P<link>(?<!\!)\[(?P<text>(?:[^\[\]]|\[[^\]]*\]){0,400}?)\]\((?P<target>[^)\s]*)(?P<title>\s+"[^"\n]*")?\))
    """,
    re.X,
)


class BuildError(Exception):
    pass


def split_segments(text):
    segs, cur, in_code, ch, ln = [], [], False, "", 0
    for line in text.split("\n"):
        if not in_code:
            m = FENCE_OPEN.match(line)
            if m and not (m.group(1)[0] == "`" and "`" in m.group(2)):
                if cur:
                    segs.append((False, "\n".join(cur)))
                cur = [line]
                in_code, ch, ln = True, m.group(1)[0], len(m.group(1))
                continue
            cur.append(line)
        else:
            cur.append(line)
            if re.match(r"^\s*(" + re.escape(ch) + "{" + str(ln) + r",})\s*$", line):
                segs.append((True, "\n".join(cur)))
                cur, in_code = [], False
    if cur:
        segs.append((in_code, "\n".join(cur)))
    return segs


def fence_mask(lines):
    mask, in_code, ch, ln = [], False, "", 0
    for line in lines:
        if not in_code:
            m = FENCE_OPEN.match(line)
            if m and not (m.group(1)[0] == "`" and "`" in m.group(2)):
                in_code, ch, ln = True, m.group(1)[0], len(m.group(1))
                mask.append(True)
                continue
            mask.append(False)
        else:
            mask.append(True)
            if re.match(r"^\s*(" + re.escape(ch) + "{" + str(ln) + r",})\s*$", line):
                in_code = False
    return mask


def headings(lines):
    mask = fence_mask(lines)
    out = []
    for i, line in enumerate(lines):
        if mask[i]:
            continue
        m = HEADING.match(line)
        if m:
            out.append((i, len(m.group(1)), m.group(2)))
    return out


def plain(h):
    h = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", h)
    return h.replace("`", "").replace("*", "").strip()


def slugify(h):
    return re.sub(r"[^\w\- ]", "", plain(h).lower()).replace(" ", "-")


def page_slugs(lines):
    seen, out = {}, {}
    for i, _, t in headings(lines):
        s = slugify(t)
        n = seen.get(s, 0)
        seen[s] = n + 1
        out[i] = s if n == 0 else f"{s}-{n}"
    return out


def title_words(words):
    return [w if (i and w.lower() in LOWER and w.islower()) else w[:1].upper() + w[1:] for i, w in enumerate(words)]


def section_name(title):
    t = re.sub(r"\(.*?\)", "", plain(title)).replace("&", " and ")
    t = re.sub(r"[—–/]", " ", t)
    t = re.sub(r"[^A-Za-z0-9. ]", "", t)
    words = t.split()
    num = re.match(r"^(\d+)\.?$", words[0]) if words else None
    prefix = f"{int(num.group(1)):02d}" if num else ""
    if num:
        words = words[1:]
    return "-".join(([prefix] if prefix else []) + title_words(words[:6]))


def derived_name(path):
    stem = re.sub(r"\.md$", "", path)
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", stem) if p]
    return "-".join(title_words(parts))


def size_of(lines, a, b):
    return sum(len(x) + 1 for x in lines[a:b])


def build_units(lines, hs, levels):
    bounds = [h for h in hs if h[1] in levels]
    starts = [b[0] for b in bounds]
    units = [(0, starts[0] if starts else len(lines), None, 0)]
    for k, b in enumerate(bounds):
        end = starts[k + 1] if k + 1 < len(starts) else len(lines)
        units.append((b[0], end, b[2], b[1]))
    return units


class Page:
    def __init__(self, name, title, body, role="page"):
        self.name, self.title, self.body, self.role = name, title, body, role
        self.raw = title
        self.units = []
        self.lineslugs = {}
        self.slugs = set()
        self.k = self.n = 0


class Doc:
    def __init__(self, repo, src, name, side, group, mode):
        self.repo, self.src, self.name, self.side, self.group, self.mode = repo, src, name, side, group, mode
        self.key = (repo, src)
        self.pages = []
        self.index = None
        self.slugmap = {}


class Builder:
    def __init__(self, sources, owner, strict=False):
        """sources maps a repository name to its checkout, the home repository first."""
        self.sources = dict(sources)
        self.strict = strict
        self.home = next(iter(self.sources))
        self.owner = owner
        self.docs = []
        self.docmap = {}
        self.unique = {}
        self.notes = []
        self.missing = []
        self.written = {}

    def blob(self, repo):
        return f"https://github.com/{self.owner}/{repo}/blob/develop/"

    def tree(self, repo):
        return f"https://github.com/{self.owner}/{repo}/tree/develop/"

    def path(self, repo, path):
        return os.path.join(self.sources[repo], path)

    def read(self, repo, path):
        with open(self.path(repo, path), encoding="utf-8") as f:
            return f.read()

    def order(self, repo):
        """order is where a path named in repo is looked for: repo itself, then the others."""
        return [repo] + [r for r in self.sources if r != repo]

    def discover(self, repo):
        found = []
        top = self.sources[repo]
        for root, dirs, files in os.walk(top):
            rel = os.path.relpath(root, top).replace(os.sep, "/")
            rel = "" if rel == "." else rel
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
            for f in sorted(files):
                path = f"{rel}/{f}" if rel else f
                if any(path.startswith(p) for p in SKIP_PREFIXES) or not f.endswith(".md"):
                    continue
                if os.path.islink(os.path.join(root, f)):
                    self.notes.append(("warning", f"{repo}: {path} is a symbolic link; not published"))
                    continue
                if (path.startswith("docs/") or (f == "README.md" and (rel or repo != self.home))
                        or path in ("AGENTS.md", "CONTRIBUTING.md")):
                    found.append(path)
        return found

    def collect(self):
        known = set()
        for repo, src, name, side, group, mode in DOCS:
            if repo not in self.sources or not os.path.exists(self.path(repo, src)):
                self.notes.append(("warning", f"{repo}: {src} is in scripts/wiki/build.py but not in the checkout"))
                continue
            if os.path.islink(self.path(repo, src)):
                self.notes.append(("warning", f"{repo}: {src} is a symbolic link; not published"))
                continue
            known.add((repo, src))
            self.docs.append(Doc(repo, src, name, side, group, mode))
        for repo in self.sources:
            for path in self.discover(repo):
                if (repo, path) in known:
                    continue
                title = re.search(r"^# (.+)$", self.read(repo, path), flags=re.M)
                side = plain(title.group(1)) if title else path
                name = derived_name(path if repo == self.home else f"{repo}/{path}")
                self.notes.append(("warning", f"{repo}: {path} is not in scripts/wiki/build.py; published as {name}"))
                self.docs.append(Doc(repo, path, name, side, "Other", None))
        names = [d.name for d in self.docs] + ["Home", "_Sidebar", "_Footer"]
        dup = {n for n in names if names.count(n) > 1}
        if dup:
            raise BuildError(f"page names collide: {sorted(dup)}")
        self.docmap = {d.key: d for d in self.docs}
        self.unique = {}
        for r, p in self.docmap:
            self.unique.setdefault(posixpath.basename(p), {}).setdefault(r, []).append(p)

    def split(self, doc, text):
        lines = text.split("\n")
        hs = headings(lines)
        h1 = next((plain(t) for _, lv, t in hs if lv == 1), doc.side)
        if doc.mode is None or len(text.encode("utf-8")) <= SPLIT_OVER:
            doc.mode = None
            doc.pages = [Page(doc.name, h1, text)]
            return
        if doc.mode == "h2":
            units = build_units(lines, hs, {2})
            doc.index = Page(doc.name, h1, "\n".join(lines[units[0][0]:units[0][1]]), "index")
            for a, b, t, _ in units[1:]:
                num = re.match(r"^\s*(\d+)", plain(t))
                name = SPEC_NAMES.get(num.group(1) if num else "") or "Spec-" + section_name(t)
                pg = Page(name, plain(t), "\n".join(lines[a:b]), "section")
                pg.raw = t
                doc.pages.append(pg)
            doc.index.units = [(p.name, p.raw, 2, 0) for p in doc.pages]
            return
        flat = []
        for a, b, t, lv in build_units(lines, hs, {2}):
            if size_of(lines, a, b) > TARGET:
                for sa, sb, st, sl in build_units(lines[a:b], headings(lines[a:b]), {3}):
                    if sb > sa:
                        flat.append((a + sa, a + sb, st if st is not None else t, sl if st is not None else lv))
            else:
                flat.append((a, b, t, lv))
        parts, cur, cur_size = [], [], 0
        for u in flat:
            sz = size_of(lines, u[0], u[1])
            if cur and cur_size + sz > TARGET:
                parts.append(cur)
                cur, cur_size = [], 0
            cur.append(u)
            cur_size += sz
        if cur:
            parts.append(cur)
        index = Page(doc.name, h1, "", "index")
        for k, part in enumerate(parts, 1):
            name = f"{doc.name}-Part-{k}"
            a, b = part[0][0], part[-1][1]
            pg = Page(name, f"{h1} (part {k} of {len(parts)})", "\n".join(lines[a:b]), "part")
            pg.k, pg.n = k, len(parts)
            doc.pages.append(pg)
            for ua, _, ut, ul in part:
                if ut is not None:
                    index.units.append((name, ut, ul, ua - a))
        doc.index = index

    def index_text(self, doc):
        text = self.read(doc.repo, doc.src)
        rebuilt = "\n".join(([doc.index.body] if doc.mode == "h2" else []) + [p.body for p in doc.pages])
        if rebuilt != text:
            raise BuildError(f"splitting {doc.repo}: {doc.src} lost text")

    def resolve_doc(self, path, doc):
        path = unquote(path)
        cands = [posixpath.normpath(path.lstrip("/"))] if path.startswith("/") else [
            posixpath.normpath(path), posixpath.normpath(posixpath.join(posixpath.dirname(doc.src), path))]
        return next(((r, c) for r in self.order(doc.repo) for c in cands if (r, c) in self.docmap), None)

    def doc_target(self, key, frag):
        d = self.docmap[key]
        if d.mode is None:
            return d.name + (("#" + frag) if frag else "")
        if frag and frag in d.slugmap:
            return d.slugmap[frag] + "#" + frag
        return d.name

    def repo_location(self, resolved, frag, doc):
        if resolved == "docs/plan" and (self.home, "docs/plan/00-overview.md") in self.docmap:
            return self.docmap[(self.home, "docs/plan/00-overview.md")].name
        tail = resolved + (("#" + frag) if frag else "")
        for repo in self.order(doc.repo):
            full = self.path(repo, resolved)
            if os.path.isdir(full):
                return self.tree(repo) + tail
            if os.path.exists(full):
                return self.blob(repo) + tail
        self.missing.append(f"{doc.repo}: {doc.src}: {resolved}")
        return self.blob(doc.repo) + tail

    def link_target(self, tgt, doc):
        if not tgt or tgt.startswith("#") or tgt.startswith("//") or URL_SCHEME.match(tgt):
            return None
        path, _, frag = tgt.partition("#")
        if not path:
            return None
        base = posixpath.normpath(unquote(path).lstrip("/") if path.startswith("/")
                                  else posixpath.join(posixpath.dirname(doc.src), unquote(path)))
        if base.startswith(".."):
            return None
        base = base.rstrip("/")
        for repo in self.order(doc.repo):
            if (repo, base) in self.docmap:
                return None if (repo, base) == doc.key and not frag else self.doc_target((repo, base), frag)
            if os.path.exists(self.path(repo, base)):
                break
        return self.repo_location(base, frag, doc)

    def by_name(self, name, doc):
        """by_name finds the page a bare file name means: the first repository in
        the linking file's order that publishes one file of that name."""
        found = self.unique.get(name, {})
        for repo in self.order(doc.repo):
            paths = found.get(repo, [])
            if paths:
                return (repo, paths[0]) if len(paths) == 1 else None
        return None

    def span_target(self, code, doc):
        m = re.fullmatch(r"([\w./\-]+\.md)(#[\w\-]+)?", code.strip())
        if not m:
            return None
        p, frag = m.group(1), (m.group(2) or "")[1:]
        if posixpath.basename(p) in ("README.md", "github.md") and "/" not in p:
            return None
        hit = self.resolve_doc(p, doc)
        if hit is None and "/" not in p:
            hit = self.by_name(p, doc)
        if hit is None or hit == doc.key:
            return None
        return self.doc_target(hit, frag)

    def rewrite(self, text, doc):
        out = []
        for is_code, seg in split_segments(text):
            if is_code:
                out.append(seg)
                continue

            def sub(m):
                if m.group("span"):
                    tgt = self.span_target(m.group("code"), doc)
                    return f"[{m.group('span')}]({tgt})" if tgt else m.group(0)
                new = self.link_target(m.group("target"), doc)
                if new is None:
                    return m.group(0)
                return f"[{m.group('text')}]({new}{m.group('title') or ''})"

            out.append(LINK_OR_SPAN.sub(sub, seg))
        return "\n".join(out)

    def footer(self, doc):
        return (f"\n\n---\n<sub>Generated from [`{doc.src}`]({self.blob(doc.repo)}{doc.src}) in {self.owner}/{doc.repo}. "
                f"Edit that file in its repository; changes made on this page are overwritten.</sub>\n{MARKER}\n")

    def nav(self, pg, doc):
        if pg.role == "part":
            bits = [f"Part {pg.k} of {pg.n} of [{doc.index.title}]({doc.name})"]
            if pg.k > 1:
                bits.append(f"[Previous]({doc.pages[pg.k - 2].name})")
            if pg.k < pg.n:
                bits.append(f"[Next]({doc.pages[pg.k].name})")
        elif pg.role == "section":
            i = doc.pages.index(pg)
            bits = [f"Section of [{doc.index.title}]({doc.name})"]
            if i > 0:
                bits.append(f"[Previous]({doc.pages[i - 1].name})")
            if i < len(doc.pages) - 1:
                bits.append(f"[Next]({doc.pages[i + 1].name})")
        else:
            return ""
        return "_" + " · ".join(bits) + "_\n\n"

    def index_body(self, doc, preamble):
        pg = doc.index
        pages = {p.name: p for p in doc.pages}
        tail = ""
        if doc.mode == "h2":
            pre = preamble.rstrip("\n").split("\n")
            h1 = next((i for i, l in enumerate(pre) if l.startswith("# ")), -1)
            lines = ["\n".join(pre[:h1 + 1]), "\n## Sections\n"]
            tail = "\n".join(pre[h1 + 1:])
        else:
            lines = [f"# {pg.title}\n",
                     f"> This document is {len(doc.pages)} pages on the wiki because GitHub renders very large pages slowly. "
                     "Headings and their anchors are unchanged; the contents below link to each one.\n",
                     "## Contents\n"]
        for name, title, lv, local in pg.units:
            pad = "" if lv <= 2 else "  "
            t = title.replace("[", "\\[").replace("]", "\\]")
            slug = pages[name].lineslugs.get(local)
            link = name if doc.mode == "h2" or not slug else f"{name}#{slug}"
            lines.append(f"{pad}- [{t}]({link})")
        out = "\n".join(lines) + "\n"
        if doc.mode == "h2":
            out += "\n## About this document\n" + tail + "\n"
        return out

    def emit(self, name, content):
        if name in self.written:
            raise BuildError(f"page {name} written twice")
        self.written[name] = content

    def sidebar(self):
        side = ["**[Home](Home)**\n"]
        for g in GROUP_ORDER:
            members = [d for d in self.docs if d.group == g]
            if not members:
                continue
            side.append(f"**{g}**\n")
            side.extend(f"- [{d.side}]({d.name})" for d in members)
            side.append("")
        return side

    def build(self):
        self.collect()
        for d in self.docs:
            text = self.read(d.repo, d.src)
            self.split(d, text)
            if d.index:
                self.index_text(d)
            for pg in ([d.index] if d.index else []) + d.pages:
                pg.lineslugs = page_slugs(pg.body.split("\n"))
                pg.slugs = set(pg.lineslugs.values())
                if pg.role != "index":
                    for sl in pg.lineslugs.values():
                        d.slugmap.setdefault(sl, pg.name)
        for d in self.docs:
            if d.index:
                self.emit(d.name, self.index_body(d, self.rewrite(d.index.body, d)) + self.footer(d))
            for pg in d.pages:
                nav = self.nav(pg, d)
                body = nav + self.rewrite(pg.body, d).rstrip("\n") + "\n"
                if nav:
                    body += "\n" + nav.rstrip("\n") + "\n"
                self.emit(pg.name, body + self.footer(d))
        home = Doc(self.home, HOME_SRC, "Home", "Home", None, None)
        readme = self.rewrite(self.read(self.home, HOME_SRC), home)
        first = readme.index("\n") + 1
        note = (f"\n> **About this wiki.** Generated from the documentation in {self.repos()} "
                "on every push to `develop` here and once a day. "
                "Edit the files there; changes made on a wiki page are overwritten.\n")
        home_map = ["\n## Wiki map\n"]
        home_map.extend(self.sidebar()[1:])
        self.emit("Home", readme[:first] + note + readme[first:].rstrip("\n") + "\n" + "\n".join(home_map).rstrip("\n") + "\n" + self.footer(home))
        self.emit("_Sidebar", "\n".join(self.sidebar()).rstrip("\n") + "\n" + MARKER + "\n")
        self.emit("_Footer", f"Generated from the documentation in {self.repos()}.\n" + MARKER + "\n")
        self.check_links()
        if self.missing:
            msg = "links name a path that no repository has:\n  " + "\n  ".join(self.missing)
            if self.strict:
                raise BuildError(msg)
            self.notes.append(("warning", msg))

    def repos(self):
        names = [f"[{r}](https://github.com/{self.owner}/{r})" for r in self.sources]
        return ", ".join(names[:-1]) + " and " + names[-1] if len(names) > 1 else names[0]

    def check_links(self):
        slugs = {}
        for d in self.docs:
            for pg in ([d.index] if d.index else []) + d.pages:
                slugs[pg.name] = pg.slugs
        bad = []
        for name, content in self.written.items():
            for is_code, seg in split_segments(content):
                if is_code:
                    continue
                for m in LINK_OR_SPAN.finditer(seg):
                    tgt = m.group("target") if m.group("link") else None
                    if not tgt or URL_SCHEME.match(tgt) or tgt.startswith("#"):
                        continue
                    p, _, frag = tgt.partition("#")
                    if p not in self.written:
                        bad.append(f"{name}: {tgt}")
                    elif frag and p in slugs and frag not in slugs[p]:
                        bad.append(f"{name}: {tgt} (no such heading)")
        if bad:
            raise BuildError("links between wiki pages do not resolve:\n  " + "\n  ".join(bad))


def write_pages(out, pages):
    os.makedirs(out, exist_ok=True)
    removed = []
    for f in sorted(os.listdir(out)):
        path = os.path.join(out, f)
        if not (f.endswith(".md") and os.path.isfile(path)) or f[:-3] in pages:
            continue
        with open(path, encoding="utf-8") as h:
            if MARKER in h.read():
                os.remove(path)
                removed.append(f[:-3])
    for name, content in pages.items():
        with open(os.path.join(out, name + ".md"), "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    return removed


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("src")
    ap.add_argument("out")
    ap.add_argument("--with", dest="others", action="append", default=[], metavar="NAME=DIR",
                    help="another repository of OWNER whose documentation the wiki publishes")
    ap.add_argument("--owner", default=os.environ.get("GITHUB_REPOSITORY_OWNER", DEFAULT_OWNER))
    ap.add_argument("--strict", action="store_true", help="fail on a link to a path no repository has")
    args = ap.parse_args(argv)
    sources = {HOME_REPO: args.src}
    for item in args.others:
        name, sep, path = item.partition("=")
        if not sep or not name or name in sources:
            ap.error(f"--with {item}: want NAME=DIR, each name once")
        sources[name] = path
    b = Builder(sources, args.owner, args.strict)
    try:
        b.build()
    except BuildError as e:
        print(f"::error::{e}")
        return 1
    for level, msg in b.notes:
        print(f"::{level}::{msg}")
    removed = write_pages(args.out, b.written)
    size = sum(len(c.encode("utf-8")) for c in b.written.values())
    print(f"{len(b.written)} pages, {size // 1024} KiB written; {len(removed)} stale pages removed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
